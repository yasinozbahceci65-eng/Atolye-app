/*
# Create public consultation photo storage

1. Purpose
- Add a dedicated Supabase Storage bucket for photos attached to expert consultation messages.
- The bucket is public because the generated image URL must be viewable by the WhatsApp recipient without a Supabase session.

2. Storage configuration
- Bucket: `consult-photos`
- Maximum file size: 8 MB.
- Allowed MIME types: JPEG, PNG, and WebP images only.

3. Security
- Enable read access only for objects in `consult-photos`.
- Allow anonymous and authenticated clients to upload consultation photos because the app supports guest usage.
- Restrict uploads to the `consult/` folder and image MIME types.
- Do not grant update or delete policies to the client; generated objects are immutable from the app.

4. Important notes
- File names are generated by the app with a random identifier and are not based on user-provided file names.
- Public URLs can be shared by WhatsApp recipients and cannot be revoked per file without changing the bucket or removing the object server-side.
*/

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'consult-photos',
  'consult-photos',
  true,
  8388608,
  ARRAY['image/jpeg', 'image/png', 'image/webp']::text[]
)
ON CONFLICT (id) DO UPDATE
SET public = EXCLUDED.public,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

DROP POLICY IF EXISTS "consult_photos_public_read" ON storage.objects;
CREATE POLICY "consult_photos_public_read"
ON storage.objects FOR SELECT
TO anon, authenticated
USING (bucket_id = 'consult-photos');

DROP POLICY IF EXISTS "consult_photos_insert" ON storage.objects;
CREATE POLICY "consult_photos_insert"
ON storage.objects FOR INSERT
TO anon, authenticated
WITH CHECK (
  bucket_id = 'consult-photos'
  AND (storage.foldername(name))[1] = 'consult'
  AND lower(COALESCE(metadata->>'mimetype', '')) IN ('image/jpeg', 'image/png', 'image/webp')
);
